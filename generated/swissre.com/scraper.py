"""
Standalone job scraper for swissre.com (India roles). Generated by the agent; runs with NO LLM calls.
Run:  python scraper.py [output.jsonl]
source_type=html_ssr, pagination=none.
"""

import sys
import json
import requests
from urllib.parse import urljoin
from bs4 import BeautifulSoup
from datetime import datetime
import html
import time

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.9",
}

_INDIA_CITY_FALLBACK = {
    "bengaluru": "Bengaluru", "bangalore": "Bangalore", "mumbai": "Mumbai", "delhi": "Delhi",
    "new delhi": "New Delhi", "gurugram": "Gurugram", "gurgaon": "Gurgaon", "noida": "Noida",
    "hyderabad": "Hyderabad", "chennai": "Chennai", "pune": "Pune", "kolkata": "Kolkata",
    "ahmedabad": "Ahmedabad",
}

def resolve_location(location_raw):
    if not location_raw:
        return (None, None, None, None)
    first_segment = location_raw.split(";")[0].strip()
    parts = [p.strip() for p in first_segment.split(",")]
    if len(parts) >= 2:
        city = parts[0] or None
        state = parts[1] if len(parts) >= 3 else None
        country_raw = parts[-1]
        if country_raw.lower() in ("india", "in"):
            return (city, state, "India", "IN")
        return (city, state, country_raw or None, None)
    bare = first_segment.lower()
    if bare in _INDIA_CITY_FALLBACK:
        return (_INDIA_CITY_FALLBACK[bare], None, "India", "IN")
    return (None, None, None, None)

def fetch_with_retries(url, headers, retries=3):
    for attempt in range(retries):
        try:
            response = requests.get(url, headers=headers, timeout=10)
            if response.status_code in {429, 500, 502, 503, 504}:
                time.sleep(2 ** attempt)
                continue
            response.raise_for_status()
            return response
        except requests.RequestException:
            time.sleep(2 ** attempt)
    return None

def ldjson_objects(soup):
    objs = []
    for tag in soup.find_all("script", type="application/ld+json"):
        try:
            data = json.loads(tag.string or "")
        except (json.JSONDecodeError, TypeError):
            continue
        items = data if isinstance(data, list) else [data]
        for it in items:
            if isinstance(it, dict):
                objs.append(it)
                if isinstance(it.get("@graph"), list):
                    objs.extend(x for x in it["@graph"] if isinstance(x, dict))
    return objs

def ldjson_get(soup, *keys):
    for o in ldjson_objects(soup):
        for k in keys:
            if o.get(k):
                return o[k]
    return None

def sel_text(soup, css):
    el = soup.select_one(css)
    return el.get_text(strip=True) if el else None

def scrape_jobs(output_path):
    jobs = []
    seen_urls = set()

    list_url = "https://www.swissre.com/careers/jobSearch.html"
    response = fetch_with_retries(list_url, HEADERS)

    if not response or response.status_code != 200:
        print("Failed to fetch job list page", file=sys.stderr)
        with open(output_path, 'w', encoding='utf-8') as f:
            pass
        return

    soup = BeautifulSoup(response.content, 'lxml')
    job_links = [urljoin(list_url, a['href']) for a in soup.find_all("a", href=True) if '/careers/job/' in a['href']]
    job_links = list(set(job_links))

    for job_url in job_links:
        if job_url in seen_urls:
            continue
        seen_urls.add(job_url)

        try:
            response = fetch_with_retries(job_url, HEADERS)
            if not response or response.status_code != 200:
                print(f"Failed to fetch job detail page {job_url}", file=sys.stderr)
                continue

            soup = BeautifulSoup(response.content, 'lxml')

            title = ldjson_get(soup, "headline", "title", "name") or sel_text(soup, "div.richtext > p > span > strong")
            if title and " | " in title:
                title = title.split(" | ")[0]

            job_id = job_url.split('/')[-1] if job_url.split('/')[-1].isdigit() else None

            location_raw = sel_text(soup, "div.richtext > p:-soup-contains('Location:')")
            if location_raw:
                location_raw = location_raw.split(":", 1)[-1].strip()
            city, state, country, country_code = resolve_location(location_raw)

            if country_code != "IN":
                continue

            job_description = max(
                (el.get_text(strip=True) for el in soup.select("div.richtext") if not el.get_text(strip=True).startswith("Location:")),
                key=len,
                default=None
            )
            job_description = html.unescape(job_description) if job_description else None

            date_posted = ldjson_get(soup, "datePublished", "datePosted")
            date_posted_text = date_posted
            try:
                date_posted = datetime.fromisoformat(date_posted).date().isoformat() if date_posted else None
            except ValueError:
                date_posted = None

            jobs.append({
                "title": html.unescape(title) if title else None,
                "job_id": job_id,
                "location": {
                    "city": city,
                    "state": state,
                    "country": country,
                    "country_code": country_code
                },
                "url": job_url,
                "apply_url": job_url,
                "date_posted": date_posted,
                "date_posted_text": date_posted_text,
                "job_description": job_description,
                "employment_type": None,
                "work_type": None,
                "salary_range": None
            })

        except Exception as e:
            print(f"Error processing {job_url}: {str(e)}", file=sys.stderr)
            continue

    with open(output_path, 'w', encoding='utf-8') as f:
        for job in jobs:
            f.write(json.dumps(job, ensure_ascii=False) + '\n')

if __name__ == "__main__":
    output_path = sys.argv[1] if len(sys.argv) > 1 else 'output.jsonl'
    scrape_jobs(output_path)