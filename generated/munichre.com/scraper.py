'''
Standalone job scraper for Munich Re (India roles). Generated by the agent; runs with NO LLM calls.
Run:  python scraper.py [output.jsonl]
source_type=html_ssr, pagination=page_number.
'''

import json
import sys
import time
import requests
from bs4 import BeautifulSoup
from urllib.parse import urljoin
from datetime import datetime
import html

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.9",
}

_INDIA_CITY_FALLBACK = {
    "bengaluru": "Bengaluru", "bangalore": "Bangalore", "mumbai": "Mumbai", "delhi": "Delhi",
    "new delhi": "New Delhi", "gurugram": "Gurugram", "gurgaon": "Gurgaon", "noida": "Noida",
    "hyderabad": "Hyderabad", "chennai": "Chennai", "pune": "Pune", "kolkata": "Kolkata",
    "ahmedabad": "Ahmedabad",
}

def resolve_location(location_raw):
    if not location_raw:
        return (None, None, None, None)
    first_segment = location_raw.split(";")[0].strip()
    parts = [p.strip() for p in first_segment.split(",")]
    if len(parts) >= 2:
        city = parts[0] or None
        state = parts[1] if len(parts) >= 3 else None
        country_raw = parts[-1]
        if country_raw.lower() in ("india", "in"):
            return (city, state, "India", "IN")
        return (city, state, country_raw or None, None)
    bare = first_segment.lower()
    if bare in _INDIA_CITY_FALLBACK:
        return (_INDIA_CITY_FALLBACK[bare], None, "India", "IN")
    return (None, None, None, None)

def fetch_with_retries(url, headers, max_retries=3):
    for attempt in range(max_retries):
        try:
            response = requests.get(url, headers=headers)
            if response.status_code == 200:
                return response
            elif response.status_code in {429, 500, 502, 503, 504}:
                time.sleep(2 ** attempt)
            elif response.status_code == 403:
                time.sleep(2 ** attempt)
        except requests.RequestException as e:
            time.sleep(2 ** attempt)
    return None

def collect_job_links(soup, page_url):
    urls = []
    for a in soup.find_all("a", href=True):
        h = a["href"]
        tail = h.rstrip("/").split("/")[-1]
        if any(k in h.lower() for k in ("/job/", "/jobs/", "/position/", "/vacancy/", "/opening/")) \
                or (tail.isdigit() and len(tail) >= 6):
            u = urljoin(page_url, h)
            if u not in urls:
                urls.append(u)
    return urls

def ldjson_objects(soup):
    objs = []
    for tag in soup.find_all("script", type="application/ld+json"):
        try:
            data = json.loads(tag.string or "")
        except (json.JSONDecodeError, TypeError):
            continue
        items = data if isinstance(data, list) else [data]
        for it in items:
            if isinstance(it, dict):
                objs.append(it)
                if isinstance(it.get("@graph"), list):
                    objs.extend(x for x in it["@graph"] if isinstance(x, dict))
    return objs

def ldjson_get(soup, *keys):
    for o in ldjson_objects(soup):
        for k in keys:
            if o.get(k):
                return o[k]
    return None

def ldjson_location(soup):
    for o in ldjson_objects(soup):
        if o.get("@type") == "JobPosting" and o.get("jobLocation"):
            locs = o["jobLocation"] if isinstance(o["jobLocation"], list) else [o["jobLocation"]]
            for l in locs:
                addr = (l or {}).get("address") or {}
                if isinstance(addr, dict) and (addr.get("addressLocality") or addr.get("addressCountry")):
                    city = addr.get("addressLocality") or None
                    state = addr.get("addressRegion") or None
                    country_raw = str(addr.get("addressCountry") or "").strip()
                    if country_raw.upper() in ("IN", "IND", "INDIA"):
                        return (city, state, "India", "IN")
                    return (city, state, country_raw or None, None)
    return None

def sel_text(soup, selector):
    el = soup.select_one(selector)
    return el.get_text(strip=True) if el else None

def main(output_path):
    base_url = "https://careers.munichre.com/en/munichre-search-results?alrpm=1269750"
    all_urls, page_number = [], 1

    while page_number <= 120:
        page_url = f"{base_url}&p={page_number}"
        resp = fetch_with_retries(page_url, HEADERS)
        if not resp or resp.status_code != 200:
            break
        links = collect_job_links(BeautifulSoup(resp.content, "lxml"), page_url)
        new_links = [u for u in links if u not in all_urls]
        if not new_links:
            break
        all_urls.extend(new_links)
        page_number += 1

    jobs = []
    for job_url in all_urls:
        try:
            resp = fetch_with_retries(job_url, HEADERS)
            if not resp or resp.status_code != 200:
                continue
            soup = BeautifulSoup(resp.content, "lxml")
            title = ldjson_get(soup, "headline", "title", "name") or sel_text(soup, ".section-35__media--container h1")
            if title and " | " in title:
                title = title.split(" | ")[0]
            job_id = sel_text(soup, ".job-id") or job_url.rstrip("/").split("/")[-1]
            location_raw = sel_text(soup, ".job-location")
            location = ldjson_location(soup) or resolve_location(location_raw)
            if location is None:
                continue
            city, state, country, country_code = location
            if country_code != "IN":
                continue
            apply_url = soup.select_one(".job-apply")["href"] if soup.select_one(".job-apply") else None
            date_posted = ldjson_get(soup, "datePosted")
            try:
                date_posted = datetime.fromisoformat(date_posted).date().isoformat() if date_posted else None
            except ValueError:
                date_posted = None
            date_posted_text = date_posted
            job_description = ldjson_get(soup, "description") or sel_text(soup, ".job-description")
            job_description = html.unescape(job_description) if job_description else None
            employment_type = sel_text(soup, ".job-employmenttype")
            work_type = sel_text(soup, ".job-workmode")
            salary_range = None

            job = {
                "title": html.unescape(title) if title else None,
                "job_id": job_id,
                "location": {"city": city, "state": state, "country": country, "country_code": country_code},
                "url": job_url,
                "apply_url": apply_url,
                "date_posted": date_posted,
                "date_posted_text": date_posted_text,
                "job_description": job_description,
                "employment_type": employment_type,
                "work_type": work_type,
                "salary_range": salary_range
            }
            jobs.append(job)
            time.sleep(0.3)
        except Exception as e:
            print(f"Error processing job at {job_url}: {e}", file=sys.stderr)

    with open(output_path, "w", encoding="utf-8") as f:
        for job in jobs:
            f.write(json.dumps(job, ensure_ascii=False) + "\n")

if __name__ == "__main__":
    output_path = sys.argv[1] if len(sys.argv) > 1 else "output.jsonl"
    main(output_path)