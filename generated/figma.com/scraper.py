"""
Standalone job scraper for Figma (India roles). Generated by the agent; runs with NO LLM calls.
Run:  python scraper.py [output.jsonl]
source_type=rest_api, pagination=none.
"""

import requests
import json
import sys
import traceback
from urllib.parse import urljoin
from datetime import datetime
import html
import time

_INDIA_CITY_FALLBACK = {
    "bengaluru": "Bengaluru", "bangalore": "Bangalore", "mumbai": "Mumbai", "delhi": "Delhi",
    "new delhi": "New Delhi", "gurugram": "Gurugram", "gurgaon": "Gurgaon", "noida": "Noida",
    "hyderabad": "Hyderabad", "chennai": "Chennai", "pune": "Pune", "kolkata": "Kolkata",
    "ahmedabad": "Ahmedabad",
}

def resolve_location(location_raw):
    # returns (city, state, country, country_code) -- all None if unresolvable, never guessed.
    if not location_raw:
        return (None, None, None, None)
    first_segment = location_raw.split(";")[0].strip()  # some platforms join multiple locations with ';'
    parts = [p.strip() for p in first_segment.split(",")]
    if len(parts) >= 2:
        # explicit "City, [State,] Country" format -- last segment is the country
        city = parts[0] or None
        state = parts[1] if len(parts) >= 3 else None
        country_raw = parts[-1]
        if country_raw.lower() in ("india", "in"):
            return (city, state, "India", "IN")
        return (city, state, country_raw or None, None)
    # no comma: bare city name -- only resolve via the small generic fallback dict, never guess otherwise
    bare = first_segment.lower()
    if bare in _INDIA_CITY_FALLBACK:
        return (_INDIA_CITY_FALLBACK[bare], None, "India", "IN")
    return (None, None, None, None)

def fetch_jobs():
    url = 'https://boards-api.greenhouse.io/v1/boards/figma/jobs'
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "en-US,en;q=0.9",
    }
    retries = 3
    backoff_factor = 1

    for attempt in range(retries):
        try:
            response = requests.get(url, headers=headers)
            if response.status_code == 200:
                return response.json()
            elif response.status_code in [429, 500, 502, 503, 504]:
                time.sleep(backoff_factor * (2 ** attempt))
            else:
                break
        except requests.RequestException:
            time.sleep(backoff_factor * (2 ** attempt))
    
    return None

def parse_jobs(data):
    jobs = data.get('jobs', [])
    india_jobs = []
    seen_job_ids = set()

    for job in jobs:
        job_id = str(job.get('id'))
        if job_id in seen_job_ids:
            continue
        seen_job_ids.add(job_id)

        title = job.get('title')
        location_raw = job.get('location', {}).get('name', '')
        url = job.get('absolute_url')
        date_posted_raw = job.get('first_published')

        city, state, country, country_code = resolve_location(location_raw)
        if country_code != "IN":
            continue

        date_posted = None
        if date_posted_raw:
            try:
                date_posted = datetime.fromisoformat(date_posted_raw).date().isoformat()
            except ValueError:
                date_posted = None

        india_jobs.append({
            "title": title,
            "job_id": job_id,
            "location": {
                "city": city,
                "state": state,
                "country": country,
                "country_code": country_code
            },
            "url": url,
            "apply_url": None,
            "date_posted": date_posted,
            "date_posted_text": date_posted_raw,
            "job_description": None,
            "employment_type": None,
            "work_type": None,
            "salary_range": None
        })

    return india_jobs

def main(output_path):
    try:
        data = fetch_jobs()
        if data is None:
            print("Failed to fetch job data.", file=sys.stderr)
            sys.exit(1)

        india_jobs = parse_jobs(data)

        with open(output_path, 'w', encoding='utf-8') as f:
            for job in india_jobs:
                f.write(json.dumps(job, ensure_ascii=False) + '\n')

    except Exception as e:
        print(f"An error occurred: {str(e)}", file=sys.stderr)
        traceback.print_exc(file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    output_path = sys.argv[1] if len(sys.argv) > 1 else 'output.jsonl'
    main(output_path)