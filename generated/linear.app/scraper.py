def scrape_jobs(output_path):
    jobs = []
    seen_urls = set()

    list_url = "https://linear.app/careers"
    response = fetch_with_retries(list_url, HEADERS)

    if not response:
        print("Failed to fetch job list page", file=sys.stderr)
        with open(output_path, 'w', encoding='utf-8') as f:
            pass
        return

    soup = BeautifulSoup(response.content, 'lxml')
    job_links = [urljoin(list_url, a['href']) for a in soup.select('a[href^="/careers/"]') if a['href'].count('/') == 3]

    for job_url in job_links:
        if job_url in seen_urls:
            continue
        seen_urls.add(job_url)

        try:
            response = fetch_with_retries(job_url, HEADERS)
            if not response:
                continue

            soup = BeautifulSoup(response.content, 'lxml')

            title = sel_text(soup, "h1.plNOQa_title")
            if title and " | " in title:
                title = title.split(" | ")[0]

            job_id = job_url.split('/')[-1]

            location_raw = sel_text(soup, "p:contains('Location & work mode') + p em")
            city, state, country, country_code = resolve_location(location_raw)

            if country_code != "IN":
                continue

            job_description = sel_text(soup, "div.plNOQa_description")
            job_description = html.unescape(job_description) if job_description else None

            employment_type = sel_text(soup, "span.sc-KOGVz.fBvCgn")

            jobs.append({
                "title": html.unescape(title) if title else None,
                "job_id": job_id,
                "location": {
                    "city": city,
                    "state": state,
                    "country": country,
                    "country_code": country_code
                },
                "url": job_url,
                "apply_url": job_url,
                "date_posted": None,
                "date_posted_text": None,
                "job_description": job_description,
                "employment_type": employment_type,
                "work_type": None,
                "salary_range": None
            })

        except Exception as e:
            print(f"Error processing {job_url}: {str(e)}", file=sys.stderr)
            continue

    with open(output_path, 'w', encoding='utf-8') as f:
        for job in jobs:
            f.write(json.dumps(job, ensure_ascii=False) + '\n')

if __name__ == "__main__":
    output_path = sys.argv[1] if len(sys.argv) > 1 else 'output.jsonl'
    scrape_jobs(output_path)