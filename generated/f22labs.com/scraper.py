#!/usr/bin/env python3
'''
Standalone job scraper for f22labs.com / f22labs.zohorecruit.in (India roles). Generated by the agent; runs with NO LLM calls.
Run:  python scraper.py [output.jsonl]
source_type=html_ssr, pagination=none.
'''

import sys
import os
import json
import time
import html
from datetime import datetime, date
from urllib.parse import urljoin, urldefrag, urlparse

import requests
from bs4 import BeautifulSoup


BASE_URL = "https://f22labs.zohorecruit.in/jobs/Careers"

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.9",
}

JOB_ANCHOR_SELECTOR = 'a[href*="/jobs/Careers/"][href*="source=CareerSite"]'

LOCATION_SELECTORS = [
    ".location",
    ".job-location",
    ".cw-location",
    ".zc-location",
    ".zr-location",
    '[class*="location"]',
]

DATE_SELECTORS = [
    ".posted-date",
    ".job-posted-date",
    ".cw-posted-date",
    '[class*="posted"]',
    '[class*="date"]',
]

EMPLOYMENT_SELECTORS = [
    ".employment-type",
    ".job-type",
    ".cw-job-type",
    '[class*="employment"]',
    '[class*="job-type"]',
]

DESCRIPTION_SELECTORS = [
    "#jobDescription",
    ".job-description",
    ".job-desc",
    ".zc-job-description",
    ".zr-job-description",
    '[class*="job-description"]',
    '[class*="description"]',
]


_INDIA_CITY_FALLBACK = {
    "bengaluru": "Bengaluru", "bangalore": "Bangalore", "mumbai": "Mumbai", "delhi": "Delhi",
    "new delhi": "New Delhi", "gurugram": "Gurugram", "gurgaon": "Gurgaon", "noida": "Noida",
    "hyderabad": "Hyderabad", "chennai": "Chennai", "pune": "Pune", "kolkata": "Kolkata",
    "ahmedabad": "Ahmedabad",
}

def resolve_location(location_raw):
    # returns (city, state, country, country_code) -- all None if unresolvable, never guessed.
    if not location_raw:
        return (None, None, None, None)
    first_segment = location_raw.split(";")[0].strip()  # some platforms join multiple locations with ';'
    parts = [p.strip() for p in first_segment.split(",")]
    if len(parts) >= 2:
        # explicit "City, [State,] Country" format -- last segment is the country
        city = parts[0] or None
        state = parts[1] if len(parts) >= 3 else None
        country_raw = parts[-1]
        if country_raw.lower() in ("india", "in"):
            return (city, state, "India", "IN")
        return (city, state, country_raw or None, None)
    # no comma: bare city name -- only resolve via the small generic fallback dict, never guess otherwise
    bare = first_segment.lower()
    if bare in _INDIA_CITY_FALLBACK:
        return (_INDIA_CITY_FALLBACK[bare], None, "India", "IN")
    return (None, None, None, None)


def collect_job_links(soup, page_url):
    urls = []
    for a in soup.find_all("a", href=True):
        h = a["href"]
        tail = h.rstrip("/").split("/")[-1]
        if any(k in h.lower() for k in ("/job/", "/jobs/", "/position/", "/vacancy/", "/opening/")) \
                or (tail.isdigit() and len(tail) >= 6):
            u = urljoin(page_url, h)
            if u not in urls:
                urls.append(u)
    return urls


def ldjson_objects(soup):
    objs = []
    for tag in soup.find_all("script", type="application/ld+json"):
        try:
            data = json.loads(tag.string or "")
        except (json.JSONDecodeError, TypeError):
            continue
        items = data if isinstance(data, list) else [data]
        for it in items:
            if isinstance(it, dict):
                objs.append(it)
                if isinstance(it.get("@graph"), list):
                    objs.extend(x for x in it["@graph"] if isinstance(x, dict))
    return objs

def ldjson_get(soup, *keys):
    for o in ldjson_objects(soup):
        for k in keys:
            if o.get(k):
                return o[k]
    return None


def ldjson_location(soup):
    for o in ldjson_objects(soup):
        if o.get("@type") == "JobPosting" and o.get("jobLocation"):
            locs = o["jobLocation"] if isinstance(o["jobLocation"], list) else [o["jobLocation"]]
            for l in locs:
                addr = (l or {}).get("address") or {}
                if isinstance(addr, dict) and (addr.get("addressLocality") or addr.get("addressCountry")):
                    city = addr.get("addressLocality") or None
                    state = addr.get("addressRegion") or None
                    country_raw = str(addr.get("addressCountry") or "").strip()
                    if country_raw.upper() in ("IN", "IND", "INDIA"):
                        return (city, state, "India", "IN")
                    return (city, state, country_raw or None, None)
    return None


def fetch_with_retries(url, headers):
    last_resp = None
    for attempt, delay in enumerate((1, 2, 4), start=1):
        try:
            resp = requests.get(url, headers=headers, timeout=30)
            last_resp = resp
            if resp.status_code == 200:
                return resp
            if resp.status_code in (403, 429) or 500 <= resp.status_code <= 599:
                if attempt < 3:
                    time.sleep(delay)
                    continue
                return resp
            return resp
        except requests.RequestException as exc:
            if attempt < 3:
                time.sleep(delay)
                continue
            print("request failed for %s: %s" % (url, exc), file=sys.stderr)
            return last_resp
    return last_resp


def normalize_url(href, base_url):
    if not href:
        return None
    absolute = urljoin(base_url, href)
    clean, _frag = urldefrag(absolute)
    return clean


def clean_text(value):
    if value is None:
        return None
    if isinstance(value, list):
        parts = []
        for item in value:
            item_text = clean_text(item)
            if item_text:
                parts.append(item_text)
        return ", ".join(parts) if parts else None
    if isinstance(value, dict):
        return None
    text = str(value).strip()
    if not text:
        return None
    return html.unescape(" ".join(text.split()))


def sel_text(root, css):
    if root is None:
        return None
    el = root.select_one(css)
    return clean_text(el.get_text(" ", strip=True)) if el else None


def first_non_empty(root, selectors):
    if root is None:
        return None
    for selector in selectors:
        try:
            elements = root.select(selector)
        except Exception:
            elements = []
        for el in elements:
            text = clean_text(el.get_text(" ", strip=True))
            if text:
                return text
    return None


def strip_location_label(text):
    text = clean_text(text)
    if not text:
        return None
    if ":" in text:
        after = text.split(":", 1)[1].strip()
        return after or None
    lower = text.lower()
    if lower == "location":
        return None
    if lower.startswith("location "):
        return text[len("location "):].strip() or None
    return text


def invalid_title(text):
    if not text:
        return True
    lower = text.strip().lower()
    bad_exact = ("apply now", "apply", "location", "posted", "posted date")
    if lower in bad_exact:
        return True
    bad_suffixes = ("location:", "posted:", "apply now:")
    for suffix in bad_suffixes:
        if lower.endswith(suffix):
            return True
    return False


def clean_title(text):
    text = clean_text(text)
    if invalid_title(text):
        return None
    if " | " in text:
        left = text.rsplit(" | ", 1)[0].strip()
        if left:
            text = left
    return text


def find_job_container(anchor):
    fallback = anchor.parent
    for parent in anchor.parents:
        if not getattr(parent, "select", None):
            continue
        try:
            links = parent.select(JOB_ANCHOR_SELECTOR)
        except Exception:
            links = []
        if len(links) == 1 and fallback is None:
            fallback = parent
        if len(links) == 1:
            has_structural_field = False
            for selectors in (LOCATION_SELECTORS, DATE_SELECTORS, EMPLOYMENT_SELECTORS):
                for selector in selectors:
                    if parent.select_one(selector):
                        has_structural_field = True
                        break
                if has_structural_field:
                    break
            if has_structural_field:
                return parent
            name = getattr(parent, "name", "")
            if name in ("li", "tr"):
                return parent
    return fallback or anchor.parent


def parse_date_to_iso(raw_text):
    raw = clean_text(raw_text)
    if not raw:
        return None
    candidate = raw
    if candidate.endswith("Z"):
        candidate = candidate[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(candidate)
        return parsed.date().isoformat()
    except (ValueError, TypeError):
        pass
    try:
        parsed_date = date.fromisoformat(raw)
        return parsed_date.isoformat()
    except (ValueError, TypeError):
        pass
    formats = (
        "%m/%d/%Y",
        "%m/%d/%y",
        "%Y-%m-%d",
        "%d-%m-%Y",
        "%d/%m/%Y",
        "%b %d, %Y",
        "%B %d, %Y",
        "%d %b %Y",
        "%d %B %Y",
        "%Y-%m-%dT%H:%M:%S%z",
        "%Y-%m-%dT%H:%M:%S.%f%z",
        "%Y-%m-%dT%H:%M:%S",
        "%Y-%m-%dT%H:%M:%S.%f",
    )
    for fmt in formats:
        try:
            return datetime.strptime(raw, fmt).date().isoformat()
        except (ValueError, TypeError):
            continue
    return None


def is_bad_description_block(text):
    text = clean_text(text)
    if not text:
        return True
    lower = text.lower()
    short_label_starts = ("location:", "posted:", "job type:", "employment type:", "apply now")
    for prefix in short_label_starts:
        if lower.startswith(prefix) and len(text) < 120:
            return True
    return False


def extract_description(soup):
    best_el = None
    best_len = 0
    seen = set()

    for selector in DESCRIPTION_SELECTORS:
        try:
            elements = soup.select(selector)
        except Exception:
            elements = []
        for el in elements:
            marker = id(el)
            if marker in seen:
                continue
            seen.add(marker)
            text = clean_text(el.get_text(" ", strip=True))
            if is_bad_description_block(text):
                continue
            text_len = len(text or "")
            if text_len > best_len:
                best_len = text_len
                best_el = el

    if best_el is not None:
        content = best_el.decode_contents().strip()
        if not content:
            content = best_el.get_text(" ", strip=True)
        content = content.strip()
        return html.unescape(content) if content else None

    meta = soup.select_one('meta[name="description"]')
    if meta and meta.get("content"):
        return clean_text(meta.get("content"))
    return None


def extract_detail_title(soup):
    title = clean_title(ldjson_get(soup, "headline", "title", "name"))
    if title:
        return title
    h1 = sel_text(soup, "h1")
    return clean_title(h1)


def detail_visible_location_raw(soup):
    raw = first_non_empty(soup, LOCATION_SELECTORS)
    return strip_location_label(raw)


def should_prefilter_by_url(entries):
    return len(entries) > 60


def india_city_path_slugs():
    slugs = []
    for city in _INDIA_CITY_FALLBACK:
        slug = city.replace(" ", "-")
        if slug not in slugs:
            slugs.append(slug)
    return slugs


def apply_url_prefilter(entries):
    if not should_prefilter_by_url(entries):
        return entries
    slugs = india_city_path_slugs()
    kept = []
    skipped = 0
    for entry in entries:
        path = urlparse(entry.get("url") or "").path.lower()
        if any(slug in path for slug in slugs):
            kept.append(entry)
        else:
            skipped += 1
    print("URL India-city prefilter skipped %d of %d detail URLs" % (skipped, len(entries)), file=sys.stderr)
    return kept


def parse_list_entries(soup):
    entries = []
    seen = set()

    collected_links = collect_job_links(soup, BASE_URL)
    collected_normalized = []
    for link in collected_links:
        normalized = normalize_url(link, BASE_URL)
        if normalized and normalized not in collected_normalized:
            collected_normalized.append(normalized)

    anchors = soup.select(JOB_ANCHOR_SELECTOR)

    for anchor in anchors:
        url = normalize_url(anchor.get("href"), BASE_URL)
        if not url or url in seen:
            continue
        seen.add(url)

        container = find_job_container(anchor)
        title = clean_title(anchor.get_text(" ", strip=True))
        location_raw = strip_location_label(first_non_empty(container, LOCATION_SELECTORS))
        employment_type = first_non_empty(container, EMPLOYMENT_SELECTORS)
        date_posted_text = first_non_empty(container, DATE_SELECTORS)

        entries.append({
            "title": title,
            "url": url,
            "location_raw": location_raw,
            "employment_type": clean_text(employment_type),
            "date_posted_text": clean_text(date_posted_text),
        })

    if not entries:
        for url in collected_normalized:
            if "/jobs/Careers/" not in url:
                continue
            if url in seen:
                continue
            seen.add(url)
            entries.append({
                "title": None,
                "url": url,
                "location_raw": None,
                "employment_type": None,
                "date_posted_text": None,
            })

    return entries


def make_record(title, url, city, state, country, country_code, date_posted_text,
                job_description, employment_type):
    return {
        "title": title,
        "job_id": None,
        "location": {
            "city": city,
            "state": state,
            "country": country,
            "country_code": country_code,
        },
        "url": url,
        "apply_url": url,
        "date_posted": parse_date_to_iso(date_posted_text),
        "date_posted_text": clean_text(date_posted_text),
        "job_description": job_description,
        "employment_type": clean_text(employment_type),
        "work_type": None,
        "salary_range": None,
    }


def write_jsonl(path, records):
    directory = os.path.dirname(os.path.abspath(path))
    if directory and not os.path.exists(directory):
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        for record in records:
            f.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n")


def scrape():
    records = []
    fatal_error = None
    detail_attempts = 0
    detail_403s = 0

    resp = fetch_with_retries(BASE_URL, HEADERS)
    if not resp or resp.status_code != 200:
        status = resp.status_code if resp is not None else "no response"
        return records, "list fetch failed for %s: %s" % (BASE_URL, status)

    soup = BeautifulSoup(resp.content, "lxml")
    entries = parse_list_entries(soup)
    entries = apply_url_prefilter(entries)

    emitted_urls = set()

    for entry in entries:
        url = entry.get("url")
        if not url or url in emitted_urls:
            continue

        preliminary_city, preliminary_state, preliminary_country, preliminary_country_code = resolve_location(entry.get("location_raw"))

        time.sleep(0.4)
        detail_attempts += 1
        try:
            detail_resp = fetch_with_retries(url, HEADERS)
            if not detail_resp or detail_resp.status_code != 200:
                status = detail_resp.status_code if detail_resp is not None else "no response"
                if status == 403:
                    detail_403s += 1
                print("skipping job detail fetch failure for %s: %s" % (url, status), file=sys.stderr)
                continue

            detail_soup = BeautifulSoup(detail_resp.content, "lxml")

            title = entry.get("title") or extract_detail_title(detail_soup)

            structured_location = ldjson_location(detail_soup)
            if structured_location:
                city, state, country, country_code = structured_location
            else:
                location_raw = entry.get("location_raw")
                if not location_raw:
                    location_raw = detail_visible_location_raw(detail_soup)
                if location_raw == entry.get("location_raw"):
                    city, state, country, country_code = (
                        preliminary_city,
                        preliminary_state,
                        preliminary_country,
                        preliminary_country_code,
                    )
                else:
                    city, state, country, country_code = resolve_location(location_raw)

            if country_code != "IN": continue

            job_description = extract_description(detail_soup)

            date_posted_text = entry.get("date_posted_text")
            if not date_posted_text:
                date_posted_text = clean_text(ldjson_get(detail_soup, "datePublished", "datePosted"))
            if not date_posted_text:
                date_posted_text = first_non_empty(detail_soup, DATE_SELECTORS)

            employment_type = entry.get("employment_type")
            if not employment_type:
                employment_type = clean_text(ldjson_get(detail_soup, "employmentType"))
            if not employment_type:
                employment_type = first_non_empty(detail_soup, EMPLOYMENT_SELECTORS)

            record = make_record(
                title=title,
                url=url,
                city=clean_text(city),
                state=clean_text(state),
                country=clean_text(country),
                country_code=clean_text(country_code),
                date_posted_text=date_posted_text,
                job_description=job_description,
                employment_type=employment_type,
            )
            records.append(record)
            emitted_urls.add(url)

        except Exception as exc:
            print("skipping job extraction failure for %s: %s" % (url, exc), file=sys.stderr)
            continue

    if detail_attempts > 0 and detail_403s == detail_attempts:
        fatal_error = "all detail page fetches returned 403 Forbidden"

    return records, fatal_error


def main():
    if len(sys.argv) > 1:
        output_path = sys.argv[1]
    else:
        script_dir = os.path.dirname(os.path.abspath(__file__))
        output_path = os.path.join(script_dir, "output.jsonl")

    records = []
    fatal_error = None

    try:
        records, fatal_error = scrape()
    except Exception as exc:
        fatal_error = "unrecoverable scraper error: %s" % exc

    try:
        write_jsonl(output_path, records)
    except Exception as exc:
        print("failed to write output file %s: %s" % (output_path, exc), file=sys.stderr)
        return 1

    if fatal_error:
        print(fatal_error, file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())