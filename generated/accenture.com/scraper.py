'''
Standalone job scraper for accenture.com (India roles). Generated by the agent; runs with NO LLM calls.
Run:  python scraper.py [output.jsonl]
Requires env var FIRECRAWL_API_KEY (renders JS/bot-protected pages). Set it first:  Windows:  set FIRECRAWL_API_KEY=fc-...   Linux/Mac:  export FIRECRAWL_API_KEY=fc-...
source_type=rendered_list_ssr_detail, pagination=unknown.
'''

import os
import sys
import json
import time
import requests
from bs4 import BeautifulSoup
from urllib.parse import urljoin
from datetime import datetime

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36",
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.9",
}

_INDIA_CITY_FALLBACK = {
    "bengaluru": "Bengaluru", "bangalore": "Bangalore", "mumbai": "Mumbai", "delhi": "Delhi",
    "new delhi": "New Delhi", "gurugram": "Gurugram", "gurgaon": "Gurgaon", "noida": "Noida",
    "hyderabad": "Hyderabad", "chennai": "Chennai", "pune": "Pune", "kolkata": "Kolkata",
    "ahmedabad": "Ahmedabad",
}

def resolve_location(location_raw):
    if not location_raw:
        return (None, None, None, None)
    first_segment = location_raw.split(";")[0].strip()
    parts = [p.strip() for p in first_segment.split(",")]
    if len(parts) >= 2:
        city = parts[0] or None
        state = parts[1] if len(parts) >= 3 else None
        country_raw = parts[-1]
        if country_raw.lower() in ("india", "in"):
            return (city, state, "India", "IN")
        return (city, state, country_raw or None, None)
    bare = first_segment.lower()
    if bare in _INDIA_CITY_FALLBACK:
        return (_INDIA_CITY_FALLBACK[bare], None, "India", "IN")
    return (None, None, None, None)

def firecrawl_render(url, scroll_times=6, wait_ms=3500):
    key = os.environ.get("FIRECRAWL_API_KEY")
    if not key:
        print("FIRECRAWL_API_KEY not set; cannot render JS page", file=sys.stderr)
        return "", []
    actions = [{"type": "wait", "milliseconds": wait_ms}]
    for _ in range(scroll_times):
        actions.append({"type": "scroll", "direction": "down"})
        actions.append({"type": "wait", "milliseconds": 1200})
    for attempt in range(3):
        try:
            r = requests.post(
                "https://api.firecrawl.dev/v1/scrape",
                headers={"Authorization": "Bearer " + key, "Content-Type": "application/json"},
                json={"url": url, "formats": ["html", "links"], "onlyMainContent": False, "actions": actions},
                timeout=120,
            )
            data = r.json()
            if data.get("success"):
                d = data.get("data", {})
                return d.get("html", "") or "", d.get("links", []) or []
        except requests.RequestException:
            pass
        time.sleep(2 ** attempt)
    return "", []

def ldjson_objects(soup):
    objs = []
    for tag in soup.find_all("script", type="application/ld+json"):
        try:
            data = json.loads(tag.string or "")
        except (json.JSONDecodeError, TypeError):
            continue
        items = data if isinstance(data, list) else [data]
        for it in items:
            if isinstance(it, dict):
                objs.append(it)
                if isinstance(it.get("@graph"), list):
                    objs.extend(x for x in it["@graph"] if isinstance(x, dict))
    return objs

def ldjson_get(soup, *keys):
    for o in ldjson_objects(soup):
        for k in keys:
            if o.get(k):
                return o[k]
    return None

def ldjson_location(soup):
    for o in ldjson_objects(soup):
        if o.get("@type") == "JobPosting" and o.get("jobLocation"):
            locs = o["jobLocation"] if isinstance(o["jobLocation"], list) else [o["jobLocation"]]
            for l in locs:
                addr = (l or {}).get("address") or {}
                if isinstance(addr, dict) and (addr.get("addressLocality") or addr.get("addressCountry")):
                    city = addr.get("addressLocality") or None
                    state = addr.get("addressRegion") or None
                    country_raw = str(addr.get("addressCountry") or "").strip()
                    if country_raw.upper() in ("IN", "IND", "INDIA"):
                        return (city, state, "India", "IN")
                    return (city, state, country_raw or None, None)
    return None

def sel_text(soup, css):
    el = soup.select_one(css)
    return el.get_text(strip=True) if el else None

def main(output_path):
    list_url = "https://www.accenture.com/in-en/careers/jobsearch"
    html, links = firecrawl_render(list_url)
    if not html:
        print("Failed to render job list page", file=sys.stderr)
        sys.exit(1)

    job_links = set(urljoin(list_url, link) for link in links if "/careers/jobdetails?id=" in link)
    if not job_links:
        with open(output_path, 'w', encoding='utf-8') as f:
            pass
        sys.exit(0)

    seen_job_ids = set()
    results = []

    for job_url in job_links:
        try:
            response = requests.get(job_url, headers=HEADERS, timeout=12)
            if response.status_code == 403:
                print(f"403 Forbidden for {job_url}, skipping", file=sys.stderr)
                continue
            response.raise_for_status()
            soup = BeautifulSoup(response.content, 'lxml')

            title = ldjson_get(soup, "headline", "title", "name") or sel_text(soup, "h1.rad-job-details-hero__title")
            job_id = sel_text(soup, "div[data-jobid]") or job_url.split("id=")[-1].split("&")[0]
            location_raw = sel_text(soup, "div[data-joblocation]")
            location = ldjson_location(soup) or resolve_location(location_raw)
            if location[3] != "IN":
                continue

            job_description = sel_text(soup, "div.rad-job-detail__primary-content")
            employment_type = sel_text(soup, "div[data-employeetype]")
            apply_url = sel_text(soup, "a.rad-job-details-hero__apply-cta[href]")

            if job_id in seen_job_ids:
                continue
            seen_job_ids.add(job_id)

            results.append({
                "title": title,
                "job_id": job_id,
                "location": {
                    "city": location[0],
                    "state": location[1],
                    "country": location[2],
                    "country_code": location[3]
                },
                "url": job_url,
                "apply_url": apply_url,
                "date_posted": None,
                "date_posted_text": None,
                "job_description": job_description,
                "employment_type": employment_type,
                "work_type": None,
                "salary_range": None
            })

        except Exception as e:
            print(f"Error processing {job_url}: {e}", file=sys.stderr)
            continue

    with open(output_path, 'w', encoding='utf-8') as f:
        for result in results:
            f.write(json.dumps(result, ensure_ascii=False) + '\n')

if __name__ == "__main__":
    output_path = sys.argv[1] if len(sys.argv) > 1 else "output.jsonl"
    main(output_path)