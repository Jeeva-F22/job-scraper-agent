def extract_card(card):
    title = first_text(card, [
        "h2", "h3", "h4",
        "[class*='job-title']",
        "[class*='jobTitle']",
        "[class*='title']",
        "[class*='Title']",
    ])
    title = normalize_title(title)

    location_raw = first_text(card, [
        "[class*='location']",
        "[class*='Location']",
        "[class*='loc']",
        "[class*='Loc']",
    ])
    location_raw = strip_leading_label(location_raw, "Location")

    desc = find_largest_description(card, scoped=False)

    detail_url = extract_link_from_scope(card)

    job_id = job_id_from_url(detail_url)
    if not job_id:
        job_id = first_text(card, [
            "[class*='reference']",
            "[class*='Reference']",
            "[class*='job-id']",
            "[class*='jobId']",
            "[class*='jobID']",
        ])
        job_id = strip_leading_label(job_id, "Job ID")

    return {
        "title": title,
        "job_id": job_id,
        "location_raw": location_raw,
        "url": detail_url,
        "job_description": desc,
    }

def infosys_india_location(location_raw):
    city, state, country, country_code = resolve_location(location_raw)
    if country_code == "IN":
        return (city, state, country, country_code)

    cleaned = strip_leading_label(location_raw, "Location")
    if cleaned:
        first_segment = cleaned.split(";")[0].strip()
        first_component = first_segment.split(",")[0].strip()
        if first_component:
            city2, state2, country2, country_code2 = resolve_location(first_component)
            if country_code2 == "IN":
                return (city2, state2, country2, country_code2)

    parsed = urlparse(LIST_URL)
    qs = parse_qs(parsed.query)
    country_param = ""
    vals = qs.get("countrycode") or qs.get("countryCode")
    if vals:
        country_param = vals[0]
    if str(country_param).upper() == "IN":
        return (city, state, "India", "IN")
    return (city, state, country, country_code)

def extract_detail(detail_url):
    page_html, _links = firecrawl_render(detail_url, scroll_times=2, wait_ms=3000)
    if not page_html.strip():
        return {}
    soup = BeautifulSoup(page_html, "lxml")

    title = ldjson_get(soup, "headline", "title", "name")
    title = normalize_title(title)
    if not title:
        title = normalize_title(first_text(soup, [
            "app-jobdesc h1",
            "app-jobdesc h2",
            "[class*='job-detail'] h1",
            "[class*='job-detail'] h2",
            "[class*='jobdesc'] h1",
            "[class*='jobdesc'] h2",
            "h1",
        ]))

    job_id = job_id_from_url(detail_url)
    if not job_id:
        job_id = first_text(soup, [
            "[class*='reference']",
            "[class*='Reference']",
            "[class*='job-id']",
            "[class*='jobId']",
            "[class*='jobID']",
        ])
        job_id = strip_leading_label(job_id, "Job ID")

    loc_tuple = ldjson_location(soup)
    location_raw = None
    if not loc_tuple:
        location_raw = first_text(soup, [
            "app-jobdesc [class*='location']",
            "app-jobdesc [class*='Location']",
            "[class*='job-detail'] [class*='location']",
            "[class*='job-detail'] [class*='Location']",
            "[class*='jobdesc'] [class*='location']",
            "[class*='jobdesc'] [class*='Location']",
        ])
        if not location_raw:
            location_raw = labeled_value(soup, ["Location"])
        location_raw = strip_leading_label(location_raw, "Location")

    desc = find_largest_description(soup, scoped=True)

    date_raw = ldjson_get(soup, "datePublished", "datePosted")
    if not date_raw:
        date_raw = labeled_value(soup, ["Posted", "Date Posted", "Posted Date"])
    date_posted, date_posted_text = parse_date(date_raw)

    employment_type = ldjson_get(soup, "employmentType")
    employment_type = clean_text(employment_type)
    if not employment_type:
        employment_type = labeled_value(soup, ["Employment Type", "Job Type"])

    return {
        "title": title,
        "job_id": job_id,
        "location_raw": location_raw,
        "location_tuple": loc_tuple,
        "url": detail_url,
        "job_description": desc,
        "date_posted": date_posted,
        "date_posted_text": date_posted_text,
        "employment_type": employment_type,
    }

def make_record(title, job_id, city, state, country, country_code, url,
                date_posted=None, date_posted_text=None, job_description=None,
                employment_type=None, work_type=None, salary_range=None):
    return {
        "title": clean_text(title),
        "job_id": clean_text(job_id),
        "location": {
            "city": clean_text(city),
            "state": clean_text(state),
            "country": clean_text(country),
            "country_code": clean_text(country_code),
        },
        "url": canonical_url(url) if url else None,
        "apply_url": None,
        "date_posted": clean_text(date_posted),
        "date_posted_text": clean_text(date_posted_text),
        "job_description": clean_text(job_description),
        "employment_type": clean_text(employment_type),
        "work_type": clean_text(work_type),
        "salary_range": clean_text(salary_range),
    }

def main():
    out_path = output_path_from_args()
    rows = []
    unrecoverable = False

    if not os.environ.get("FIRECRAWL_API_KEY"):
        write_jsonl(out_path, [])
        print("FIRECRAWL_API_KEY not set. Set it first: Windows: set FIRECRAWL_API_KEY=fc-... ; Linux/Mac: export FIRECRAWL_API_KEY=fc-...", file=sys.stderr)
        return 1

    try:
        list_html, list_links = firecrawl_render(LIST_URL, scroll_times=15, wait_ms=4000)
        if not list_html.strip():
            write_jsonl(out_path, [])
            print("error: rendered Infosys job list was empty/unreachable", file=sys.stderr)
            return 1

        soup = BeautifulSoup(list_html, "lxml")
        cards = card_elements(soup)
        records = []
        seen_record_keys = set()

        for card in cards:
            try:
                data = extract_card(card)
                key = data.get("job_id") or data.get("url")
                if not key:
                    if data.get("title") or data.get("location_raw"):
                        key = (data.get("title") or "") + "||" + (data.get("location_raw") or "")
                if not key or key in seen_record_keys:
                    continue
                seen_record_keys.add(key)
                records.append(data)
            except Exception as e:
                print("card extraction error: " + str(e), file=sys.stderr)
                continue

        for detail_url in detail_urls_from_links_and_html(list_links, soup):
            jid = job_id_from_url(detail_url)
            key = jid or detail_url
            if key in seen_record_keys:
                continue
            seen_record_keys.add(key)
            records.append({
                "title": None,
                "job_id": jid,
                "location_raw": None,
                "url": detail_url,
                "job_description": None,
            })

        if not records:
            write_jsonl(out_path, [])
            return 0

        emitted = set()
        for base in records:
            try:
                detail = {}
                detail_url = base.get("url")
                if detail_url:
                    try:
                        detail = extract_detail(detail_url)
                        time.sleep(0.3)
                    except Exception as e:
                        print("detail extraction error for " + str(detail_url) + ": " + str(e), file=sys.stderr)
                        detail = {}

                title = detail.get("title") or base.get("title")
                job_id = detail.get("job_id") or base.get("job_id") or job_id_from_url(detail_url)
                url = detail.get("url") or detail_url

                location_tuple = detail.get("location_tuple")
                if location_tuple:
                    city, state, country, country_code = location_tuple
                else:
                    location_raw = detail.get("location_raw") or base.get("location_raw")
                    city, state, country, country_code = infosys_india_location(location_raw)

                if country_code != "IN": continue

                job_description = detail.get("job_description") or base.get("job_description")
                date_posted = detail.get("date_posted")
                date_posted_text = detail.get("date_posted_text")
                employment_type = detail.get("employment_type")

                dedupe_key = job_id or url
                if not dedupe_key:
                    dedupe_key = (title or "") + "||" + (base.get("location_raw") or "")
                if not dedupe_key or dedupe_key in emitted:
                    continue
                emitted.add(dedupe_key)

                rows.append(make_record(
                    title=title,
                    job_id=job_id,
                    city=city,
                    state=state,
                    country=country,
                    country_code=country_code,
                    url=url,
                    date_posted=date_posted,
                    date_posted_text=date_posted_text,
                    job_description=job_description,
                    employment_type=employment_type,
                    work_type=None,
                    salary_range=None,
                ))
            except Exception as e:
                print("job extraction error for " + str(base.get("url")) + ": " + str(e), file=sys.stderr)
                continue

    except Exception as e:
        unrecoverable = True
        print("error: unrecoverable Infosys scrape failure: " + str(e), file=sys.stderr)

    write_jsonl(out_path, rows)
    if unrecoverable:
        return 1
    return 0

if __name__ == "__main__":
    sys.exit(main())